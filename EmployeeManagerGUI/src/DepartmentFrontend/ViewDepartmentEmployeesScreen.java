    public boolean fillTable(Department dep)
    {
         ArrayList<Employee> depEmps= DepartmentManager.getDepEmps(dep);
         DefaultTableModel m= (DefaultTableModel)jTable1.getModel() ;
         m.setRowCount(0);
         if(depEmps.isEmpty())
         {
             return false;
         }
         for (Employee e : depEmps)
         {
             m.addRow(new Object[]{e.getEmployeeID(), e.getFirstName(), e.getLastName(), e.getEmployeeType(), e.getEmployeePosition()});
         }
         return true;
    }
