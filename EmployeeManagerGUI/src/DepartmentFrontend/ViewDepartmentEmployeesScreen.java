    private void displayButtonActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_displayButtonActionPerformed
        // TODO add your handling code here:
        if(depComboBox.getSelectedItem()==null)
        {
            JOptionPane.showMessageDialog(this, "No departments exist");
            return;
        }
        if(EmployeeManager.employees.isEmpty())
        {
            JOptionPane.showMessageDialog(this, "No employees");
            return;
        }
        //else fill the table. but check if there are no employees first.
        String selectedDep= (String) depComboBox.getSelectedItem();
        for(Department d: DepartmentManager.getDepList())
        {
            if(selectedDep.trim().equalsIgnoreCase(d.getName().trim()))
            {
                if(!fillTable(d))
                {
                    JOptionPane.showMessageDialog(this, "There are no employees in this department");
                    return;
                }
            }
        }
    }//GEN-LAST:event_displayButtonActionPerformed

